const i18n = i18next.createInstance();
await i18n.init({
  resources: Object.fromEntries(
    Object.entries(messages).map(([locale, translation]) => [locale, { translation }])
  ),
  lng: "zh-CN",
  fallbackLng: "zh-CN",
  supportedLngs: SUPPORTED_LANGUAGES,
  keySeparator: false,
  nsSeparator: false,
  interpolation: {
    prefix: "{",
    suffix: "}",
    escapeValue: false
  },
  initImmediate: false
});

let language = "zh-CN";

function normalizeLanguage(value) {
  return String(value ?? "").toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

export function getLanguage() {
  return language;
}

export function getLocale() {
  return language;
}

export async function setLanguage(nextLanguage, options = {}) {
  language = normalizeLanguage(nextLanguage);
  await i18n.changeLanguage(language);
  if (options.persist !== false && typeof localStorage !== "undefined") {
    try {
      localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
    } catch {
      // Language switching still works when storage is unavailable.
    }
  }
  applyStaticTranslations();
  return language;
}

export async function initializeLanguage() {
  let stored = null;
  if (typeof localStorage !== "undefined") {
    try {
      stored = localStorage.getItem(LANGUAGE_STORAGE_KEY);
    } catch {
      stored = null;
    }
  }
  const preferences =
    typeof navigator !== "undefined"
      ? navigator.languages?.length
        ? navigator.languages
        : [navigator.language]
      : [];
  const preferred = preferences.find(Boolean) ?? "zh-CN";
  await setLanguage(stored || preferred, { persist: false });
  return language;
}

export function t(key, values = {}) {
  return String(i18n.t(key, values));
}

export function plural(key, count, values = {}) {
  const variant = language === "en" && Number(count) === 1 ? "one" : "other";
  return t(`${key}.${variant}`, { count, ...values });
}

export function applyStaticTranslations(root = typeof document !== "undefined" ? document : null) {
  if (!root) return;
  for (const node of root.querySelectorAll("[data-i18n]")) {
    node.textContent = t(node.dataset.i18n);
  }
  for (const node of root.querySelectorAll("[data-i18n-placeholder]")) {
    node.setAttribute("placeholder", t(node.dataset.i18nPlaceholder));
  }
  for (const node of root.querySelectorAll("[data-i18n-aria-label]")) {
    node.setAttribute("aria-label", t(node.dataset.i18nAriaLabel));
  }
  for (const node of root.querySelectorAll("[data-i18n-title]")) {
    node.setAttribute("title", t(node.dataset.i18nTitle));
  }
  for (const node of root.querySelectorAll("[data-i18n-content]")) {
    node.setAttribute("content", t(node.dataset.i18nContent));
  }
  document.documentElement.lang = language;
  document.title = t("meta.title");
}
